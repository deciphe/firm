def glyph_name(ch):
    return 'space' if ch == ' ' else f'uni{ord(ch):04X}'


def draw(rows):
    pen = TTGlyphPen(None)
    width = max(len(r) for r in rows)
    for r, row in enumerate(rows):
        y0 = (6 - r) * P
        x = 0
        while x < len(row):
            if row[x] == '#':
                start = x
                while x < len(row) and row[x] == '#':
                    x += 1
                # one rectangle per horizontal run (clockwise for TrueType)
                pen.moveTo((start * P, y0))
                pen.lineTo((start * P, y0 + P))
                pen.lineTo((x * P, y0 + P))
                pen.lineTo((x * P, y0))
                pen.closePath()
            else:
                x += 1
    return pen.glyph(), (width + 1) * P


def embolden(rows):
    """Bold cut: every pixel also fills the pixel to its right (one column wider)."""
    out = []
    for row in rows:
        r = row + '.'
        out.append(''.join('#' if r[i] == '#' or (i > 0 and r[i - 1] == '#') else '.' for i in range(len(r))))
    return out


def build(out_path, bold=False):
    order = ['.notdef'] + [glyph_name(c) for c in G]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(c): glyph_name(c) for c in G})
    glyphs, metrics = {}, {}
    nd = TTGlyphPen(None)
    for x0, y0, x1, y1 in [(0, 0, 500, 700)]:
        nd.moveTo((x0, y0)); nd.lineTo((x0, y1)); nd.lineTo((x1, y1)); nd.lineTo((x1, y0)); nd.closePath()
    glyphs['.notdef'] = nd.glyph(); metrics['.notdef'] = (600, 0)
    for c, rows in G.items():
        gl, adv = draw(embolden(rows) if bold and c != ' ' else rows)
        glyphs[glyph_name(c)] = gl
        metrics[glyph_name(c)] = (adv, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=900, descent=-300)
    fb.setupNameTable({'familyName': 'FIRM Pixel Bold' if bold else 'FIRM Pixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=900, sTypoDescender=-300, sTypoLineGap=0, usWinAscent=900, usWinDescent=300, sxHeight=500, sCapHeight=700)
    fb.setupPost()
    fb.save(out_path)


